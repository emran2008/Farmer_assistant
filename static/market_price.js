function goBack() {

  /*
   * যদি bazar.html আলাদা পেজ হিসেবে খোলা হয়,
   * আগের পেজে ফিরে যাবে।
   */

  if (
    window.history.length > 1
  ) {

    window.history.back();

    return;

  }


  /*
   * History না থাকলে Farmer Assistant-এর
   * মূল পেজে যাওয়ার চেষ্টা করবে।
   */

  window.location.href =
    "market_price.html";

}