/* =========================================================
   LOAD DISTRICTS
   ========================================================= */

function loadDistricts() {

  const division =
    divisionSelect.value;


  resetSelect(
    districtSelect,
    "জেলা নির্বাচন করুন"
  );

  resetSelect(
    upazilaSelect,
    "প্রথমে জেলা নির্বাচন করুন"
  );

  resetSelect(
    marketSelect,
    "প্রথমে উপজেলা নির্বাচন করুন"
  );


  districtSelect.disabled = true;
  upazilaSelect.disabled = true;
  marketSelect.disabled = true;


  if (!division) {

    updateStatus(
      "📍 প্রথমে আপনার বিভাগ নির্বাচন করুন"
    );

    return;
  }


  const districts =
    districtData[division] || [];


  districts.forEach(
    function (district) {

      const option =
        document.createElement("option");

      option.value =
        district;

      option.textContent =
        district;

      districtSelect.appendChild(
        option
      );

    }
  );


  districtSelect.disabled = false;


  updateStatus(
    "✅ " +
    division +
    " বিভাগ নির্বাচন করা হয়েছে — এখন জেলা নির্বাচন করুন"
  );

}


