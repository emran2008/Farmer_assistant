/* =========================================================
   MARKET CHANGE
   ========================================================= */

function marketChanged() {

  if (!marketSelect.value) {

    updateStatus(
      "📍 বাজার নির্বাচন করুন"
    );

    return;
  }


  updateStatus(
    "✅ নির্বাচিত এলাকা: " +
    getLocation()
  );

}


/* =========================================================
   RESET SELECT
   ========================================================= */

function resetSelect(
  select,
  text
) {

  if (!select) {
    return;
  }


  select.innerHTML = "";


  const option =
    document.createElement("option");

  option.value = "";

  option.textContent = text;

  select.appendChild(option);

}


/* =========================================================
   STATUS
   ========================================================= */

function updateStatus(
  message
) {

  if (statusBox) {

    statusBox.textContent =
      message;

  }

}


/* =========================================================
   GET LOCATION
   ========================================================= */

function getLocation() {

  const division =
    divisionSelect.value;

  const district =
    districtSelect.value;

  const upazila =
    upazilaSelect.value;

  const market =
    marketSelect.value;


  let location = "";


  if (division) {

    location +=
      division;

  }


  if (district) {

    location +=
      " → " +
      district;

  }


  if (upazila) {

    location +=
      " → " +
      upazila;

  }


  if (market) {

    location +=
      " → " +
      market;

  }


  return location;

}


/* =========================================================
   VALIDATE
   ========================================================= */

function validateLocation() {

  if (!divisionSelect.value) {

    showError(
      "⚠️ প্রথমে বিভাগ নির্বাচন করুন।"
    );

    return false;

  }


  if (!districtSelect.value) {

    showError(
      "⚠️ প্রথমে জেলা নির্বাচন করুন।"
    );

    return false;

  }


  if (!upazilaSelect.value) {

    showError(
      "⚠️ প্রথমে উপজেলা নির্বাচন করুন।"
    );

    return false;

  }


  if (!marketSelect.value) {

    showError(
      "⚠️ প্রথমে বাজার নির্বাচন করুন।"
    );

    return false;

  }


  return true;

}


/* =========================================================
   ERROR
   ========================================================= */

function showError(
  message
) {

  resultBox.innerHTML =

    '<div class="market-error">' +

      message +

    '</div>';


  resultBox.scrollIntoView({
    behavior: "smooth",
    block: "start"
  });

}


