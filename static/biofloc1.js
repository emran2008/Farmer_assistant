/* =========================================================
   Dropdown তৈরি + মাছ নির্বাচন
========================================================= */

let selectedFish = null;

const fishSelect = document.getElementById("fishSelect");

// Dropdown-এ সব মাছ যোগ করা
Object.keys(fishData).forEach(fishName => {
    const option = document.createElement("option");
    option.value = fishName;
    option.textContent = `${fishName} (${fishData[fishName].en})`;
    fishSelect.appendChild(option);
});

// Dropdown change হলে
fishSelect.addEventListener("change", function () {
    const name = this.value;

    if (!name) {
        document.getElementById("fishInfoSection").classList.add("hidden");
        selectedFish = null;
        return;
    }

    selectedFish = name;
    showFishInfo(name);
    document.getElementById("fishInfoSection").classList.remove("hidden");

    document.getElementById("fishInfoSection")
        .scrollIntoView({ behavior: "smooth", block: "start" });
});


