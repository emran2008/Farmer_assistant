/* =========================================================
   BIOFLOC CHECK
========================================================= */

function checkBiofloc() {

    if (!selectedFish) {
        alert("দয়া করে প্রথমে মাছ নির্বাচন করুন!");
        return;
    }

    const temperature = Number(document.getElementById("temperature").value);
    const ph = Number(document.getElementById("ph").value);
    const doValue = Number(document.getElementById("do").value);
    const ammonia = Number(document.getElementById("ammonia").value);
    const nitrite = Number(document.getElementById("nitrite").value);
    const biofloc = Number(document.getElementById("biofloc").value);

    const length = Number(document.getElementById("length").value);
    const width = Number(document.getElementById("width").value);
    const depth = Number(document.getElementById("depth").value);
    const fishCount = Number(document.getElementById("fishCount").value);
    const feed = Number(document.getElementById("feed").value);

    const volume = length * width * depth;
    const density = volume > 0 ? fishCount / volume : 0;
    const flocAmount = volume * biofloc;

    document.getElementById("waterVolume").innerText = volume.toFixed(2) + " m³";
    document.getElementById("density").innerText = density.toFixed(1) + " মাছ/m³";
    document.getElementById("dailyFeed").innerText = feed.toFixed(2) + " kg/day";
    document.getElementById("flocAmount").innerText = flocAmount.toFixed(2) + " L";

    document.getElementById("calculation").classList.remove("hidden");

    /* পানি বিশ্লেষণ */
    const analysis = [];
    const fish = fishData[selectedFish];
    const tempRange = getRange(fish.temp);

    if (temperature >= tempRange.min && temperature <= tempRange.max) {
        analysis.push({ name: "Temperature", value: temperature + "°C", status: "good", text: "✓ আদর্শ" });
    } else {
        analysis.push({ name: "Temperature", value: temperature + "°C", status: "danger", text: "আদর্শ নয়" });
    }

    if (ph >= 6.5 && ph <= 8) {
        analysis.push({ name: "pH", value: ph, status: "good", text: "✓ আদর্শ" });
    } else {
        analysis.push({ name: "pH", value: ph, status: "danger", text: "pH ঠিক করুন" });
    }

    if (doValue >= 5) {
        analysis.push({ name: "DO", value: doValue + " mg/L", status: "good", text: "✓ পর্যাপ্ত" });
    } else {
        analysis.push({ name: "DO", value: doValue + " mg/L", status: "danger", text: "Aeration বাড়ান" });
    }

    if (ammonia <= 0.05) {
        analysis.push({ name: "Ammonia", value: ammonia + " mg/L", status: "good", text: "✓ নিরাপদ" });
    } else {
        analysis.push({ name: "Ammonia", value: ammonia + " mg/L", status: "danger", text: "বেশি" });
    }

    if (nitrite <= 0.5) {
        analysis.push({ name: "Nitrite", value: nitrite + " mg/L", status: "good", text: "✓ নিরাপদ" });
    } else {
        analysis.push({ name: "Nitrite", value: nitrite + " mg/L", status: "danger", text: "বেশি" });
    }

    if (biofloc >= 15 && biofloc <= 25) {
        analysis.push({ name: "Biofloc", value: biofloc + " mL/L", status: "good", text: "✓ আদর্শ" });
    } else {
        analysis.push({ name: "Biofloc", value: biofloc + " mL/L", status: "warning", text: "সমন্বয় প্রয়োজন" });
    }

    document.getElementById("analysisGrid").innerHTML = analysis.map(item => `
        <div class="analysis-item ${item.status}">
            <strong>${item.name}</strong>
            <small>${item.value}</small>
            <small>${item.text}</small>
        </div>
    `).join("");

    document.getElementById("waterAnalysis").classList.remove("hidden");

    /* CONDITION */
    let problems = [];
    if (doValue < 5) problems.push("DO কম");
    if (ph < 6.5 || ph > 8) problems.push("pH আদর্শ নয়");
    if (ammonia > 0.05) problems.push("Ammonia বেশি");
    if (nitrite > 0.5) problems.push("Nitrite বেশি");

    if (problems.length === 0) {
        document.getElementById("conditionBox").innerHTML = `
            <div class="condition-box good">
                <div class="condition-title">Biofloc-এর অবস্থা ভালো</div>
                <div>বর্তমানে বড় কোনো পানি-সংক্রান্ত সমস্যা পাওয়া যায়নি। নিয়মিত পানি পরীক্ষা এবং Aeration চালু রাখুন।</div>
            </div>
        `;
    } else {
        document.getElementById("conditionBox").innerHTML = `
            <div class="condition-box danger">
                <div class="condition-title">⚠️ মনোযোগ প্রয়োজন</div>
                <div>${problems.join(" • ")}</div>
            </div>
        `;
    }

    document.getElementById("condition").classList.remove("hidden");

    /* ADVICE */
    let advice = [];

    if (doValue < 5) {
        advice.push("DO কম — Aerator সবসময় পর্যাপ্তভাবে চালু রাখুন এবং পানিতে অক্সিজেন নিশ্চিত করুন।");
    } else {
        advice.push("DO বর্তমানে ভালো আছে — Aeration নিয়মিত পর্যবেক্ষণ করুন।");
    }

    if (ph < 6.5 || ph > 8) {
        advice.push("pH আদর্শ সীমার বাইরে — ধীরে ধীরে pH সমন্বয় করুন।");
    } else {
        advice.push("pH বর্তমানে গ্রহণযোগ্য সীমায় আছে।");
    }

    if (ammonia > 0.05) {
        advice.push("☠️ Ammonia বেশি — Feed কমানো, Aeration বৃদ্ধি এবং Biofloc-এর ভারসাম্য পরীক্ষা করুন।");
    }

    if (nitrite > 0.5) {
        advice.push("⚠️ Nitrite বেশি — পানির গুণমান পরীক্ষা করুন এবং Biofloc system-এর microbial balance বজায় রাখুন।");
    }

    advice.push("প্রতিদিন Temperature, pH, DO, Ammonia ও Nitrite পরীক্ষা করুন।");
    advice.push("মাছের biomass অনুযায়ী Feed দিন এবং অতিরিক্ত খাবার দেওয়া এড়িয়ে চলুন।");
    advice.push("Biofloc-এর ঘনত্ব নিয়মিত পর্যবেক্ষণ করুন এবং প্রয়োজন অনুযায়ী ব্যবস্থাপনা করুন।");

    document.getElementById("adviceList").innerHTML = advice.map(text => `
        <div class="advice-item">${text}</div>
    `).join("");

    document.getElementById("advice").classList.remove("hidden");

    document.getElementById("calculation").scrollIntoView({ behavior: "smooth", block: "start" });
}


/* Temperature Range Helper */
function getRange(text) {
    const numbers = text.match(/\d+(\.\d+)?/g);
    return {
        min: Number(numbers[0]),
        max: Number(numbers[1])
    };
}