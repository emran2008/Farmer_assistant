def seed_fish_data():

    conn = get_connection()

    query = """
    INSERT OR IGNORE INTO fish_species (
        fish_name,
        min_temperature,
        max_temperature,
        min_ph,
        max_ph,
        min_do,
        max_do,
        min_alkalinity,
        max_alkalinity,
        recommended_stocking_density,
        feeding_rate,
        expected_growth,
        culture_period_days
    )
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """

    conn.executemany(query, fish_data)

    conn.commit()
    conn.close()

    print("========================================")
    print("Biofloc fish data inserted successfully.")
    print(f"Total species: {len(fish_data)}")
    print("========================================")


if __name__ == "__main__":
    seed_fish_data()